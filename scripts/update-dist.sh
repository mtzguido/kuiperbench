#!/usr/bin/env bash
# Updates dist/ from obj/ and regenerates BUILD_INFO only when
# the generated .cu/.h files have actually changed.

set -euo pipefail

changed=0

for f in obj/*.cu obj/*.h; do
    base=$(basename "$f")
    dst="dist/$base"
    if [[ ! -f "$dst" ]] || ! cmp -s "$f" "$dst"; then
        changed=1
        break
    fi
done

# Also check for files removed from obj/ but still present in dist/
for f in dist/*.cu dist/*.h; do
    [[ -e "$f" ]] || continue
    base=$(basename "$f")
    if [[ ! -f "obj/$base" ]]; then
        changed=1
        break
    fi
done

if [[ "$changed" -eq 0 ]]; then
    echo "dist/ is up to date."
    exit 0
fi

rm -f dist/*.cu dist/*.h
cp obj/*.cu obj/*.h dist

kuiper_home="${KUIPER_HOME:-$PWD/.kuiper}"
kuiper_build="unknown"
if [[ -f "$kuiper_home/BUILD_INFO" ]]; then
    kuiper_build=$(sed -n 's/^Kuiper commit:[[:space:]]*//p' "$kuiper_home/BUILD_INFO")
fi

cat > dist/BUILD_INFO <<EOF
Generated by KuiperBench using the selected Kuiper package
Kuiper commit: $kuiper_build
EOF

echo "dist/ updated."
